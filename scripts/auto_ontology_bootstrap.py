"""Make a freshly started local Auto Ontology ready for Omniq: token, compilation, readiness.

  1. sign in as the local admin (credentials generated by scripts/auto_ontology.sh)
  2. mint an API token for Omniq → var/auto-ontology-token (development fallback; see ARCHITECTURE 4.8)
  3. switch semantic compilation on and wait until the warehouse is compiled

Usage: .venv/bin/python scripts/auto_ontology_bootstrap.py [--wait-minutes 60]
"""

from __future__ import annotations

import argparse
import os
import pathlib
import sys
import time

import httpx

ROOT = pathlib.Path(__file__).resolve().parents[1]
AO_ENV = ROOT / "var" / "vendor" / "auto-ontology" / ".env"
TOKEN_FILE = ROOT / "var" / "auto-ontology-token"
URL = os.environ.get("OA_AO_URL", "http://localhost:3000").rstrip("/")


def _env() -> dict[str, str]:
    out = {}
    for line in AO_ENV.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wait-minutes", type=float, default=60)
    args = ap.parse_args()
    env = _env()
    c = httpx.Client(base_url=URL, timeout=60, headers={"Origin": URL})

    for _ in range(60):  # the web app may still be starting
        try:
            if c.get("/api/health").status_code < 500:
                break
        except httpx.HTTPError:
            pass
        time.sleep(5)
    r = c.post("/api/auth/sign-in/email", json={"email": env["AUTO_ONTOLOGY_ADMIN_EMAIL"],
                                                 "password": env["AUTO_ONTOLOGY_ADMIN_PASSWORD"]})
    r.raise_for_status()
    print("signed in as admin")

    if not TOKEN_FILE.exists():
        r = c.post("/api/api-tokens", json={"name": "omniq-dev"})
        r.raise_for_status()
        TOKEN_FILE.write_text(r.json()["token"])
        TOKEN_FILE.chmod(0o600)
        print(f"API token written to {TOKEN_FILE}")
    token = TOKEN_FILE.read_text().strip()
    api = httpx.Client(base_url=URL, timeout=60, headers={"x-api-key": token})

    r = c.put("/api/configurations/semantic-compilation", json={"enabled": True})
    r.raise_for_status()
    print("semantic compilation enabled")

    deadline = time.time() + args.wait_minutes * 60
    last = None
    while time.time() < deadline:
        s = api.get("/api/semantic-compilation/status")
        body = s.json() if s.headers.get("content-type", "").startswith("application/json") else {"raw": s.text[:200]}
        if body != last:
            print("status:", body, flush=True)
            last = body
        data = body.get("data", body) if isinstance(body, dict) else {}
        if data.get("ready") or data.get("calculated") or data.get("has_terms"):
            terms = api.get("/api/terms", params={"limit": 100})
            print("compiled; terms:", terms.status_code, str(terms.json())[:400])
            return 0
        time.sleep(20)
    print("compilation did not finish in time", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
