#!/usr/bin/env bash
# Run NVIDIA Auto Ontology locally as Omniq's structured-data engine, on local models only.
#
#   scripts/auto_ontology.sh up       clone the pinned release, write its .env, build, start, load the warehouse
#   scripts/auto_ontology.sh load     (re)load the Halcyon warehouse into its Postgres
#   scripts/auto_ontology.sh status   container state
#   scripts/auto_ontology.sh down     stop the stack (data volumes are kept)
#
# Everything lives under var/vendor/auto-ontology (git-ignored). Models are served by the host's Ollama through
# its OpenAI-compatible API, so no NVIDIA or other hosted key is needed. Secrets are generated once into
# var/auto-ontology.env and reused.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO_URL="https://github.com/NVIDIA/auto-ontology.git"
PIN="c4495670947eb7b4616f0dd9900e5ced2a48ca1e"   # v1.2.0
DIR="$ROOT/var/vendor/auto-ontology"
SECRETS="$ROOT/var/auto-ontology.env"
WAREHOUSE_SQL="$ROOT/var/warehouse/halcyon.postgres.sql"

OLLAMA="${OA_AO_OLLAMA_URL:-http://host.docker.internal:11434/v1}"
REASONING_MODEL="${OA_AO_REASONING_MODEL:-gemma4:12b}"
FAST_MODEL="${OA_AO_FAST_MODEL:-gemma4:e4b}"
EMBED_MODEL="${OA_AO_EMBED_MODEL:-hf.co/CompendiumLabs/bge-base-en-v1.5-gguf:latest}"
PG_PORT="${OA_AO_POSTGRES_PORT:-5433}"

compose() { (cd "$DIR" && docker compose "$@"); }

secret() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-32}"; }

ensure_source() {
  if [ ! -d "$DIR/.git" ]; then
    mkdir -p "$(dirname "$DIR")"
    git clone -q "$REPO_URL" "$DIR"
  fi
  (cd "$DIR" && git fetch -q --depth 1 origin "$PIN" 2>/dev/null || true; git checkout -q "$PIN")
}

ensure_secrets() {
  if [ ! -f "$SECRETS" ]; then
    mkdir -p "$(dirname "$SECRETS")"
    umask 077
    cat >"$SECRETS" <<EOF
POSTGRES_PASSWORD=$(secret 24)
AUTH_SECRET=$(secret 48)
AUTO_ONTOLOGY_ADMIN_PASSWORD=$(secret 20)
PGADMIN_PASSWORD=$(secret 20)
EOF
  fi
  # shellcheck disable=SC1090
  . "$SECRETS"
}

write_env() {
  cat >"$DIR/.env" <<EOF
# Generated by omniq scripts/auto_ontology.sh. Do not edit; edit the script or var/auto-ontology.env.
POSTGRES_HOST=localhost
POSTGRES_PORT=$PG_PORT
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_DATABASE=auto_ontology
CONNECTION_STRINGS=postgresql://postgres:$POSTGRES_PASSWORD@postgres:5432/halcyon
PGADMIN_EMAIL=admin@halcyonlabs.example
PGADMIN_PASSWORD=$PGADMIN_PASSWORD
DEFAULT_MODELS_API_KEY=ollama
DEFAULT_MODELS_ENDPOINT=$OLLAMA
DEFAULT_MODELS_MODEL=$REASONING_MODEL
REASONING_API_KEY=ollama
REASONING_ENDPOINT=$OLLAMA
REASONING_MODEL=$REASONING_MODEL
NON_REASONING_API_KEY=ollama
NON_REASONING_ENDPOINT=$OLLAMA
NON_REASONING_MODEL=$FAST_MODEL
EMBED_API_KEY=ollama
EMBED_ENDPOINT=$OLLAMA
EMBED_MODEL=$EMBED_MODEL
# No local reranker: Auto Ontology only reranks bridge-table candidates at compile time and tolerates failure.
RERANK_ENDPOINT=http://127.0.0.1:9/v1/ranking
RERANK_MODEL=none
RERANK_API_KEY=none
APP_URL=http://localhost:3000
AUTO_ONTOLOGY_MCP_PUBLIC_URL=http://localhost:3003
INGESTION_SERVICE_URL=http://localhost:3002
AUTO_ONTOLOGY_ADMIN_EMAIL=admin@halcyonlabs.example
AUTO_ONTOLOGY_ADMIN_PASSWORD=$AUTO_ONTOLOGY_ADMIN_PASSWORD
AUTH_SECRET=$AUTH_SECRET
EOF
}

load_warehouse() {
  [ -f "$WAREHOUSE_SQL" ] || "$ROOT/.venv/bin/python" "$ROOT/scripts/build_warehouse.py"
  compose up -d --wait postgres
  compose exec -T postgres psql -q -U postgres -v ON_ERROR_STOP=1 -c "DROP DATABASE IF EXISTS halcyon WITH (FORCE);" \
    -c "CREATE DATABASE halcyon;"
  compose exec -T postgres psql -q -U postgres -v ON_ERROR_STOP=1 -d halcyon <"$WAREHOUSE_SQL"
  echo "warehouse loaded into postgres/halcyon"
}

case "${1:-up}" in
  up)
    ensure_source; ensure_secrets; write_env
    load_warehouse
    compose up -d --build
    echo "Auto Ontology: http://localhost:3000 (admin login in $SECRETS and $DIR/.env)"
    ;;
  load) ensure_secrets; load_warehouse ;;
  status) compose ps ;;
  down) compose down ;;
  *) echo "usage: $0 up|load|status|down" >&2; exit 2 ;;
esac
